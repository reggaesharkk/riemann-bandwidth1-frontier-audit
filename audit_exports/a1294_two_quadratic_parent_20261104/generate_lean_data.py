#!/usr/bin/env python3
"""Generate Lean literals from the bounded, authenticated node-65 ledger.

This is a serialization aid only.  Lean proves segment coverage, source-piece
checks, rank tangents, child predicates and parent coverage independently.
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
LEDGER = HERE / "siblings_normal.json"
OUT = HERE / "A1294TwoQuadraticParent.lean"


def q(s: str) -> str:
    return s if "/" in s else s


def emit() -> str:
    data = json.loads(LEDGER.read_text(encoding="utf-8"))
    out = ["-- Generated by generate_lean_data.py from siblings_normal.json."]
    for side in ("left", "right"):
        child = data["children"][side]
        for term in child["fifteen_models"]:
            p = term["pair_index_zero_based"]
            if term["kind"] != "segmented_constant" or term["base"] == "0":
                continue
            name = f"segments_{side}_{p}"
            lo, hi = term["distance_interval"]
            floor = term["base"]
            out.append(f"def {name} : List SourceSegment := [")
            rows = []
            for seg in term["segments"]:
                decl = seg["declaration"]
                check = decl + "_check"
                rows.append(
                    "  { lo := " + q(seg["segment"][0]) +
                    ", hi := " + q(seg["segment"][1]) +
                    ", piece := " + decl + " }"
                )
            out.append(",\n".join(rows))
            out.append("]")
            row_checks = []
            for j, seg in enumerate(term["segments"]):
                decl = seg["declaration"]
                check_name = f"{name}_segment_{j}_checked"
                row_checks.append(check_name)
                lo_seg, hi_seg = seg["segment"]
                out.append(
                    f"theorem {check_name} : sourceSegmentCheck ({floor}) "
                    f"{{ lo := {q(lo_seg)}, hi := {q(hi_seg)}, piece := {decl} }} = true := by\n"
                    f"  norm_num [sourceSegmentCheck, segmentMinimum, clampRational, "
                    f"{decl}, MacroPiece.box]\n"
                )
            out.append(
                f"theorem {name}_accepted : sourcePiecewiseCheck "
                f"({lo}) ({hi}) ({floor}) {name} = true := by\n"
                f"  have hlen : decide (0 < {name}.length) = true := by norm_num [{name}]\n"
                f"  have hcover : sourceCoverFrom ({lo}) ({hi}) {name} = true := by\n"
                f"    norm_num [sourceCoverFrom, {name}]\n"
                f"  have hall : {name}.all (sourceSegmentCheck ({floor})) = true := by\n"
                f"    simp only [{name}, List.all_cons, List.all_nil, "
                + ", ".join(row_checks)
                + ", Bool.true_and]\n"
                f"  simp [sourcePiecewiseCheck, hlen, hcover, hall]"
            )
            out.append(
                f"theorem {name}_pieces_checked : ∀ s ∈ {name}, s.piece.check = true := by"
            )
            out.append("  intro s hs")
            out.append(
                f"  simp only [{name}, List.mem_cons, List.mem_nil_iff, or_false] at hs"
            )
            rows = term["segments"]
            out.append("  rcases hs with " + " | ".join("h" for _ in rows))
            for seg in rows:
                out.append(f"  · cases h; exact {seg['declaration']}_check")
            out.append("")
    generated_rows = "\n".join(out) + "\n"
    prototype = (HERE / "SegmentPrototype.lean").read_text(encoding="utf-8")
    generic = prototype.split("def piece3Well :", 1)[0]
    generic = generic.replace(
        "import Zeta23.ThmD.Sextuple.AffineTree\n",
        "import Zeta23.ThmD.Sextuple.AffineTree\n"
        "import Zeta23.ThmD.Sextuple.Macro.AffineAdapter\n",
        1,
    )
    return generic + generated_rows + "\nend A1294TwoQuadraticParent\n"


if __name__ == "__main__":
    text = emit()
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(text)} bytes)")
